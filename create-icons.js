const fs = require('fs');
const path = require('path');

// 创建一个简单的PNG图标（1x1像素的白色PNG）
// 这是一个最小的PNG文件，实际应用中应该使用真正的图标
const pngData = Buffer.from([
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,  // PNG签名
  0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,  // IHDR块
  0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,  // 1x1像素
  0x08, 0x02, 0x00, 0x00, 0x00, 0x90, 0x77, 0x53,  // 8位RGB
  0xDE, 0x00, 0x00, 0x00, 0x0C, 0x49, 0x44, 0x41,  // IDAT块
  0x54, 0x08, 0xD7, 0x63, 0xF8, 0xCF, 0xC0, 0x00,  // 压缩数据
  0x00, 0x00, 0x02, 0x00, 0x01, 0xE2, 0x21, 0xBC,  // 
  0x33, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E,  // IEND块
  0x44, 0xAE, 0x42, 0x60, 0x82
]);

// 创建build/icons目录
const iconsDir = path.join(__dirname, 'build', 'icons');
if (!fs.existsSync(iconsDir)) {
  fs.mkdirSync(iconsDir, { recursive: true });
}

// 保存PNG图标
fs.writeFileSync(path.join(iconsDir, 'icon.png'), pngData);
console.log('Created icon.png');

// 对于Windows和macOS，我们需要转换格式
// 这里我们只是创建占位符文件，实际应用中需要使用真正的图标
fs.writeFileSync(path.join(iconsDir, 'icon.ico'), pngData);
console.log('Created icon.ico (placeholder)');

fs.writeFileSync(path.join(iconsDir, 'icon.icns'), pngData);
console.log('Created icon.icns (placeholder)');

console.log('Icons created successfully!');